static uint8_t* g_cyber_home_raw = nullptr;
static lv_image_dsc_t g_cyber_home_dsc;

static inline const lv_image_dsc_t* getCyberHomeImage() {
    if (g_cyber_home_raw == nullptr) {
        size_t outsize = 0;
        unsigned err = lodepng_zlib_decompress(&g_cyber_home_raw, &outsize,
                                               cyber_home_image_zlib,
                                               sizeof(cyber_home_image_zlib),
                                               &lodepng_default_decompress_settings);
        if (err != 0 || g_cyber_home_raw == nullptr || outsize != 320 * 216 * 2) {
            if (g_cyber_home_raw != nullptr) {
                lv_free(g_cyber_home_raw);
                g_cyber_home_raw = nullptr;
            }
            return nullptr;
        }
        g_cyber_home_dsc.header.magic = LV_IMAGE_HEADER_MAGIC;
        g_cyber_home_dsc.header.cf = LV_COLOR_FORMAT_RGB565;
        g_cyber_home_dsc.header.flags = 0;
        g_cyber_home_dsc.header.w = 320;
        g_cyber_home_dsc.header.h = 216;
        g_cyber_home_dsc.header.stride = 640;
        g_cyber_home_dsc.header.reserved_2 = 0;
        g_cyber_home_dsc.data_size = 320 * 216 * 2;
        g_cyber_home_dsc.data = g_cyber_home_raw;
        g_cyber_home_dsc.reserved = nullptr;
        g_cyber_home_dsc.reserved_2 = nullptr;
    }
    return &g_cyber_home_dsc;
}

static inline void freeCyberHomeImage() {
    if (g_cyber_home_raw != nullptr) {
        lv_free(g_cyber_home_raw);
        g_cyber_home_raw = nullptr;
    }
}
